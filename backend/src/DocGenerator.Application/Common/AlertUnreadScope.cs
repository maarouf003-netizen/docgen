namespace DocGenerator.Application.Common;

/// <summary>
/// نطاق عدّاد غير المقروء (`D6`/`D7`، الخطة §5/المرحلة 4) — يمنع التباسًا بين
/// رقمين مختلفين يحملان الاسم نفسه:
///
/// <list type="bullet">
/// <item><see cref="User"/>: صفوف الاستلام **العائدة للفاعل نفسه**؛ المحامي بلا قيد
/// فرع، والرئيس/الشعبة داخل فرعه فقط — مطابقةً لقائمته (D7).</item>
/// <item><see cref="Received"/>: كل صفوف غير المقروءة على **التنبيهات التي استلمها
/// الرئيس** في فرعه (لا صفّه وحده) — مطابقةً لمجموع <c>unreadCount</c> في القائمة
/// القديمة **غير المرقّمة**، وهي شارة لوحة الحساب (D6).</item>
/// </list>
///
/// <para><b>سطح مؤقت (`ح‑26`):</b> وُجد <see cref="Received"/> لحفظ رقم الشارة في
/// <c>PR-5</c>؛ ويُحسم في <c>PR-6</c> هل تبقى الشارة تجميعية أم تصير
/// <see cref="User"/> بعد إزالة عدّادات التفاصيل. عند التحول يُحذف النطاق مع
/// اختبار يثبت رفضه — لا يُترك سطحًا ميتًا.</para>
/// </summary>
public enum AlertUnreadScope
{
    /// <summary>عدّ صفوف استلام الفاعل نفسه (الافتراضي — عقد ما قبل المرحلة 4).</summary>
    User = 0,

    /// <summary>عدّ غير المقروء على التنبيهات التي استلمها الرئيس في فرعه (رئيس/شعبة فقط).</summary>
    Received = 1,
}
