namespace DocGenerator.Domain.Entities;

/// <summary>
/// حجز صريح لأصل فيزيائي لصالح إنابة حاجبة (B3 — نقطة التسلسل لسباق التسطير المتزامن):
/// صف لكل أصل مختار في إنابة سارية حاجبة، بقيد فريد على (المنيب + الأصل) يمنع
/// إنابتين متزامنتين من حجز الأصل نفسه حتى لو تجاوزتا فحص القراءة معًا.
///
/// ملاحظة تصميمية مقصودة: المرجع إلى الأصل «مرتخٍ» (AssetId بلا مفتاح أجنبي إلى Assets)،
/// لأن أصول الملف تُعاد بناؤها بمعرفات جديدة عند كل تعديل — فمفتاح Restrict كان سيكسر
/// تحديث الملف، وCascade كان سيمسح الحجوزات مع كل تعديل. تُشتق الصفوف من ربط
/// (الإنابات الحاجبة × الأصول الحالية) وتُعاد مواءمتها في مسارات الإنابة، وتُعاد بناؤها
/// كاملةً عند كل تعديل للمنيب (تزامن اللقطات) — فأي انحراف يُشفى ذاتيًا. والحارس يفحص
/// مسح اللقطات حصرًا (عمدًا لا اتحاد مع الحجوزات — الاتحاد يختلف على التوأم المحجوب
/// فيحجب السليم)؛ والقيد الفريد وحده نقطة التسلسل عند الكتابة.
/// </summary>
public class DelegationAssetReservation
{
    public int Id { get; set; }

    /// <summary>الإنابة الحاجبة مالكة الحجز — حذفها يحذف صفوفها تتاليًا.</summary>
    public int DelegationId { get; set; }

    /// <summary>الملف المنيب (مكرر للاستعلام المباشر وطرف القيد الفريد).</summary>
    public int SourceDocumentId { get; set; }

    /// <summary>المعرف الفيزيائي للأصل المحجوز وقت الحجز (مرجع مرتخٍ — انظر أعلاه).</summary>
    public int AssetId { get; set; }

    public DocumentDelegation Delegation { get; set; } = null!;
}
