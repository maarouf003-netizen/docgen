/**
 * خطأ مخالفة عقد سلكي: جسم الاستجابة وصل بشكل لا يطابق الشكل المتفق عليه بين
 * الخلفي والواجهة (نحو جسم ليس `PagedResult` أو `items` غير مصفوفة).
 *
 * يُرمى من طبقة `api/` **عمدًا** بدل تمرير قيمة ناقصة تُخفي العطل (صفحة فارغة
 * كاذبة، جدول بلا أعمدة، عدّاد صفر…)؛ فتصل إلى مسار الخطأ القائم (لافتة + إعادة
 * محاولة) ويُبلَّغ عنها. رسالته عربية مصوغة للعرض المباشر لأن مصدرها كودنا لا
 * الخادم، ولهذا يعترف بها `getApiErrorMessage` ويعيدها كما هي — بخلاف أي
 * `Error` عائم تبقى رسالته عامة (منع تسريب رسائل داخلية).
 */
export class ContractError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'ContractError';
  }
}
